static void
replace_control_chars (char *cell)
{
  char *p = cell;
  while (*p)
    {
      if (c_iscntrl (to_uchar (*p)))
        *p = '?';
      p++;
    }
}



static void
replace_invalid_chars (char *cell)
{
  char *srcend = cell + strlen (cell);
  char *dst = cell;
  mbstate_t mbstate = { 0, };
  size_t n;

  for (char *src = cell; src != srcend; src += n)
    {
      wchar_t wc;
      size_t srcbytes = srcend - src;
      n = 
         rpl_mbrtowc 
                 (&wc, src, srcbytes, &mbstate);
      
     _Bool 
          ok = n <= srcbytes;

      if (ok)
        ok = !iswcntrl (wc);
      else
        n = 1;

      if (ok)
        {
          memmove (dst, src, n);
          dst += n;
        }
      else
        {
          *dst++ = '?';
          memset (&mbstate, 0, sizeof mbstate);
        }
    }

  *dst = '\0';
}

