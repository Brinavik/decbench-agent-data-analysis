static void
add_uint_with_neg_flag (uintmax_t *dest, 
                                        _Bool 
                                             *dest_neg,
                        uintmax_t src, 
                                      _Bool 
                                           src_neg)
{
  if (*dest_neg == src_neg)
    {
      *dest += src;
      return;
    }

  if (*dest_neg)
    *dest = -*dest;

  if (src_neg)
    src = -src;

  if (src < *dest)
    *dest -= src;
  else
    {
      *dest = src - *dest;
      *dest_neg = src_neg;
    }

  if (*dest_neg)
    *dest = -*dest;
}




