static char *
scan_diff_line (char *scan_ptr, char **set_start, size_t *set_length,
                char *limit, char leadingchar)
{
  char *line_ptr;

  if (!(scan_ptr[0] == leadingchar
        && scan_ptr[1] == ' '))
    fatal ("invalid diff format; incorrect leading line chars");

  *set_start = line_ptr = scan_ptr + 2;
  while (*line_ptr++ != '\n')
    continue;






  *set_length = line_ptr - *set_start;
  if (line_ptr < limit && *line_ptr == '\\')
    {
      if (edscript)
        fprintf (
                stderr
                      , "%s:", program_name);
      else
        --*set_length;
      line_ptr++;
      do
        {
          if (edscript)
            putc_unlocked (*line_ptr,
           stderr
           );
        }
      while (*line_ptr++ != '\n');
    }

  return line_ptr;
}
static void
output_diff3 (FILE *outputfile, struct diff3_block *diff,
              int const mapping[3], int const rev_mapping[3])
{
  int i;
  int oddoneout;
  char *cp;
  struct diff3_block *ptr;
  lin line;
  size_t length;
  int dontprint;
  static int skew_increment[3] = { 2, 3, 1 };
  char const *line_prefix = initial_tab ? "\t" : "  ";

  for (ptr = diff; ptr; ptr = ((ptr)->next))
    {
      char x[2];

      switch (ptr->correspond)
        {
        case DIFF_ALL:
          x[0] = 0;
          dontprint = 3;
          oddoneout = 3;
          break;
        case DIFF_1ST:
        case DIFF_2ND:
        case DIFF_3RD:
          oddoneout = rev_mapping[ptr->correspond - DIFF_1ST];

          x[0] = oddoneout + '1';
          x[1] = 0;
          dontprint = oddoneout == 0;
          break;
        default:
          fatal ("internal error: invalid diff type passed to output");
        }
      fprintf (outputfile, "====%s\n", x);


      for (i = 0; i < 3;
           i = (oddoneout == 1 ? skew_increment[i] : i + 1))
        {
          int realfile = mapping[i];
          lin lowt = ((ptr)->ranges[realfile][0]);
          lin hight = ((ptr)->ranges[realfile][1]);
          printint llowt = lowt;
          printint lhight = hight;

          fprintf (outputfile, "%d:", i + 1);
          switch (lowt - hight)
            {
            case 1:
              fprintf (outputfile, "%""l""da\n", llowt - 1);
              break;
            case 0:
              fprintf (outputfile, "%""l""dc\n", llowt);
              break;
            default:
              fprintf (outputfile, "%""l""d,%""l""dc\n", llowt, lhight);
              break;
            }

          if (i == dontprint) continue;

          if (lowt <= hight)
            {
              line = 0;
              do
                {
                  fputs_unlocked (line_prefix,outputfile);
                  cp = ((ptr)->lines[realfile][line]);
                  length = ((ptr)->lengths[realfile][line]);
                  fwrite_unlocked (cp,sizeof (char),length,outputfile);
                }
              while (++line < hight - lowt + 1);
              if (cp[length - 1] != '\n')
                fprintf (outputfile, "\n\\ %s\n",
                         gettext ("No newline at end of file"));
            }
        }
    }
}





static 
      _Bool

dotlines (FILE *outputfile, struct diff3_block *b, int filenum)
{
  lin i;
  
 _Bool 
      leading_dot = 
                    0
                         ;

  for (i = 0;
       i < (((b)->ranges[filenum][1]) - ((b)->ranges[filenum][0]) + 1);
       i++)
    {
      char *line = ((b)->lines[filenum][i]);
      if (line[0] == '.')
        {
          leading_dot = 
                       1
                           ;
          fputc_unlocked ('.',outputfile);
        }
      fwrite_unlocked (line,sizeof (char),((b)->lengths[filenum][i]),outputfile)
                                                   ;
    }

  return leading_dot;
}





static void
undotlines (FILE *outputfile, 
                             _Bool 
                                  leading_dot, printint start, printint num)
{
  fputs_unlocked (".\n",outputfile);
  if (leading_dot)
    {
      if (num == 1)
        fprintf (outputfile, "%""l""ds/^\\.//\n", start);
      else
        fprintf (outputfile, "%""l""d,%""l""ds/^\\.//\n", start, start + num - 1);
    }
}
static 
      _Bool

output_diff3_edscript (FILE *outputfile, struct diff3_block *diff,
                       int const mapping[3], int const rev_mapping[3],
                       char const *file0, char const *file1, char const *file2)
{
  
 _Bool 
      leading_dot;
  
 _Bool 
      conflicts_found = 
                        0
                             ;
  
 _Bool 
      conflict;
  struct diff3_block *b;

  for (b = reverse_diff3_blocklist (diff); b; b = b->next)
    {

      enum diff_type type
        = (b->correspond == DIFF_ALL
           ? DIFF_ALL
           : DIFF_1ST + rev_mapping[b->correspond - DIFF_1ST]);

      printint low0, high0;


      switch (type)
        {
        default: continue;
        case DIFF_2ND: if (!show_2nd) continue; conflict = 
                                                          1
                                                              ; break;
        case DIFF_3RD: if (overlap_only) continue; conflict = 
                                                             0
                                                                  ; break;
        case DIFF_ALL: if (simple_only) continue; conflict = flagging; break;
        }

      low0 = ((b)->ranges[mapping[0]][0]);
      high0 = ((b)->ranges[mapping[0]][1]);

      if (conflict)
        {
          conflicts_found = 
                           1
                               ;




          fprintf (outputfile, "%""l""da\n", high0);
          leading_dot = 
                       0
                            ;
          if (type == DIFF_ALL)
            {
              if (show_2nd)
                {

                  fprintf (outputfile, "||||||| %s\n", file1);
                  leading_dot = dotlines (outputfile, b, mapping[1]);
                }

              fputs_unlocked ("=======\n",outputfile);
              leading_dot |= dotlines (outputfile, b, mapping[2]);
            }
          fprintf (outputfile, ">>>>>>> %s\n", file2);
          undotlines (outputfile, leading_dot, high0 + 2,
                      ((((b)->ranges[mapping[1]][1]) - ((b)->ranges[mapping[1]][0]) + 1)
                       + (((b)->ranges[mapping[2]][1]) - ((b)->ranges[mapping[2]][0]) + 1) + 1));




          fprintf (outputfile, "%""l""da\n<<<<<<< %s\n", low0 - 1,
                   type == DIFF_ALL ? file0 : file1);
          leading_dot = 
                       0
                            ;
          if (type == DIFF_2ND)
            {

              leading_dot = dotlines (outputfile, b, mapping[1]);
              fputs_unlocked ("=======\n",outputfile);
            }
          undotlines (outputfile, leading_dot, low0 + 1,
                      (((b)->ranges[mapping[1]][1]) - ((b)->ranges[mapping[1]][0]) + 1));
        }
      else if ((((b)->ranges[mapping[2]][1]) - ((b)->ranges[mapping[2]][0]) + 1) == 0)

        {
          if (low0 == high0)
            fprintf (outputfile, "%""l""dd\n", low0);
          else
            fprintf (outputfile, "%""l""d,%""l""dd\n", low0, high0);
        }
      else

        {
          switch (high0 - low0)
            {
            case -1:
              fprintf (outputfile, "%""l""da\n", high0);
              break;
            case 0:
              fprintf (outputfile, "%""l""dc\n", high0);
              break;
            default:
              fprintf (outputfile, "%""l""d,%""l""dc\n", low0, high0);
              break;
            }

          undotlines (outputfile, dotlines (outputfile, b, mapping[2]),
                      low0, (((b)->ranges[mapping[2]][1]) - ((b)->ranges[mapping[2]][0]) + 1));
        }
    }
  if (finalwrite)
    fputs_unlocked ("w\nq\n",outputfile);
  return conflicts_found;
}
static 
      _Bool

output_diff3_merge (FILE *infile, FILE *outputfile, struct diff3_block *diff,
                    int const mapping[3], int const rev_mapping[3],
                    char const *file0, char const *file1, char const *file2)
{
  int c;
  lin i;
  
 _Bool 
      conflicts_found = 
                        0
                             ;
  
 _Bool 
      conflict;
  struct diff3_block *b;
  lin linesread = 0;

  for (b = diff; b; b = b->next)
    {

      enum diff_type type
        = ((b->correspond == DIFF_ALL)
           ? DIFF_ALL
           : DIFF_1ST + rev_mapping[b->correspond - DIFF_1ST]);
      char const *format_2nd = "<<<<<<< %s\n";


      switch (type)
        {
        default: continue;
        case DIFF_2ND: if (!show_2nd) continue; conflict = 
                                                          1
                                                              ; break;
        case DIFF_3RD: if (overlap_only) continue; conflict = 
                                                             0
                                                                  ; break;
        case DIFF_ALL: if (simple_only) continue; conflict = flagging;
          format_2nd = "||||||| %s\n";
          break;
        }


      i = ((b)->ranges[0][0]) - linesread - 1;
      linesread += i;
      while (0 <= --i)
        do
          {
            c = getc_unlocked (infile);
            if (c == 
                    (-1)
                       )
              {
                if (ferror_unlocked (infile))
                  perror_with_exit (gettext ("read failed"));
                else if (feof_unlocked (infile))
                  fatal ("input file shrank");
              }
            putc_unlocked (c,outputfile);
          }
        while (c != '\n');

      if (conflict)
        {
          conflicts_found = 
                           1
                               ;

          if (type == DIFF_ALL)
            {

              fprintf (outputfile, "<<<<<<< %s\n", file0);
              for (i = 0;
                   i < (((b)->ranges[mapping[0]][1]) - ((b)->ranges[mapping[0]][0]) + 1);
                   i++)
                fwrite_unlocked (((b)->lines[mapping[0]][i]),sizeof (char),((b)->lengths[mapping[0]][i]),outputfile)
                                                                    ;
            }

          if (show_2nd)
            {

              fprintf (outputfile, format_2nd, file1);
              for (i = 0;
                   i < (((b)->ranges[mapping[1]][1]) - ((b)->ranges[mapping[1]][0]) + 1);
                   i++)
                fwrite_unlocked (((b)->lines[mapping[1]][i]),sizeof (char),((b)->lengths[mapping[1]][i]),outputfile)
                                                                    ;
            }

          fputs_unlocked ("=======\n",outputfile);
        }


      for (i = 0;
           i < (((b)->ranges[mapping[2]][1]) - ((b)->ranges[mapping[2]][0]) + 1);
           i++)
        fwrite_unlocked (((b)->lines[mapping[2]][i]),sizeof (char),((b)->lengths[mapping[2]][i]),outputfile)
                                                            ;

      if (conflict)
        fprintf (outputfile, ">>>>>>> %s\n", file2);


      i = (((b)->ranges[0][1]) - ((b)->ranges[0][0]) + 1);
      linesread += i;
      while (0 <= --i)
        while ((c = getc_unlocked (infile)) != '\n')
          if (c == 
                  (-1)
                     )
            {
              if (ferror_unlocked (infile))
                perror_with_exit (gettext ("read failed"));
              else if (feof_unlocked (infile))
                {
                  if (i || b->next)
                    fatal ("input file shrank");
                  return conflicts_found;
                }
            }
    }

  while ((c = getc_unlocked (infile)) != 
                               (-1) 
                                   || !(ferror_unlocked (infile) | feof_unlocked (infile)))
    putc_unlocked (c,outputfile);
  return conflicts_found;
}



static struct diff3_block *
reverse_diff3_blocklist (struct diff3_block *diff)
{
  register struct diff3_block *tmp, *next, *prev;

  for (tmp = diff, prev = 0; tmp; tmp = next)
    {
      next = tmp->next;
      tmp->next = prev;
      prev = tmp;
    }

  return prev;
}

