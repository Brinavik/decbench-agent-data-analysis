static struct diff3_block *
make_3way_diff (struct diff_block *thread0, struct diff_block *thread1)
{
  struct diff_block *using[2];
  struct diff_block *last_using[2];
  struct diff_block *current[2];

  lin high_water_mark;

  int high_water_thread;
  int base_water_thread;
  int other_thread;

  struct diff_block *high_water_diff;
  struct diff_block *other_diff;

  struct diff3_block *result;
  struct diff3_block *tmpblock;
  struct diff3_block **result_end;

  struct diff3_block const *last_diff3;

  static struct diff3_block const zero_diff3;


  result = 0;
  result_end = &result;
  current[0] = thread0; current[1] = thread1;
  last_diff3 = &zero_diff3;



  while (current[0] || current[1])
    {
      using[0] = using[1] = last_using[0] = last_using[1] = 0;


      if (!current[0])
        base_water_thread = 1;
      else if (!current[1])
        base_water_thread = 0;
      else
        base_water_thread =
          (((current[0])->ranges[1][0]) > ((current[1])->ranges[1][0]));

      high_water_thread = base_water_thread;

      high_water_diff = current[high_water_thread];

      high_water_mark = ((high_water_diff)->ranges[1][1]);


      using[high_water_thread]
        = last_using[high_water_thread]
        = high_water_diff;
      current[high_water_thread] = high_water_diff->next;
      last_using[high_water_thread]->next = 0;


      other_thread = high_water_thread ^ 0x1;
      other_diff = current[other_thread];



      while (other_diff
             && ((other_diff)->ranges[1][0]) <= high_water_mark + 1)
        {



          if (using[other_thread])
            last_using[other_thread]->next = other_diff;
          else
            using[other_thread] = other_diff;
          last_using[other_thread] = other_diff;




          current[other_thread] = current[other_thread]->next;
          other_diff->next = 0;







          if (high_water_mark < ((other_diff)->ranges[1][1]))
            {
              high_water_thread ^= 1;
              high_water_mark = ((other_diff)->ranges[1][1]);
            }


          other_thread = high_water_thread ^ 0x1;
          other_diff = current[other_thread];
        }




      tmpblock = using_to_diff3_block (using, last_using,
                                       base_water_thread, high_water_thread,
                                       last_diff3);

      if (!tmpblock)
        fatal ("internal error: screwup in format of diff blocks");


      *result_end = tmpblock;
      result_end = &tmpblock->next;


      last_diff3 = tmpblock;
    }
  return result;
}
static struct diff3_block *
using_to_diff3_block (struct diff_block *using[2],
                      struct diff_block *last_using[2],
                      int low_thread, int high_thread,
                      struct diff3_block const *last_diff3)
{
  lin low[2], high[2];
  struct diff3_block *result;
  struct diff_block *ptr;
  int d;
  lin i;


  lin lowc = ((using[low_thread])->ranges[1][0]);
  lin highc = ((last_using[high_thread])->ranges[1][1]);





  for (d = 0; d < 2; d++)
    if (using[d])
      {
        low[d] = ((lowc) - (((using[d]))->ranges[(1)][0]) + (((using[d]))->ranges[(0)][0]));
        high[d] = ((highc) - (((last_using[d]))->ranges[(1)][1]) + (((last_using[d]))->ranges[(0)][1]));
      }
    else
      {
        low[d] = ((lowc) - (((last_diff3))->ranges[(2)][1]) + (((last_diff3))->ranges[(0 + d)][1]));
        high[d] = ((highc) - (((last_diff3))->ranges[(2)][1]) + (((last_diff3))->ranges[(0 + d)][1]));
      }


  result = create_diff3_block (low[0], high[0], low[1], high[1], lowc, highc);




  for (d = 0; d < 2; d++)
    for (ptr = using[d]; ptr; ptr = ((ptr)->next))
      {
        lin result_offset = ((ptr)->ranges[1][0]) - lowc;

        if (!copy_stringlist (((ptr)->lines[1]),
                              ((ptr)->lengths[1]),
                              ((result)->lines[2]) + result_offset,
                              ((result)->lengths[2]) + result_offset,
                              (((ptr)->ranges[1][1]) - ((ptr)->ranges[1][0]) + 1)))
          return 0;
      }




  for (d = 0; d < 2; d++)
    {
      struct diff_block *u = using[d];
      lin lo = low[d], hi = high[d];

      for (i = 0;
           i + lo < (u ? ((u)->ranges[0][0]) : hi + 1);
           i++)
        {
          ((result)->lines[0 + d][i]) = ((result)->lines[2][i]);
          ((result)->lengths[0 + d][i]) = ((result)->lengths[2][i]);
        }

      for (ptr = u; ptr; ptr = ((ptr)->next))
        {
          lin result_offset = ((ptr)->ranges[0][0]) - lo;
          lin linec;

          if (!copy_stringlist (((ptr)->lines[0]),
                                ((ptr)->lengths[0]),
                                ((result)->lines[0 + d]) + result_offset,
                                ((result)->lengths[0 + d]) + result_offset,
                                (((ptr)->ranges[0][1]) - ((ptr)->ranges[0][0]) + 1)))
            return 0;


          linec = ((ptr)->ranges[1][1]) + 1 - lowc;
          for (i = ((ptr)->ranges[0][1]) + 1 - lo;
               i < (((ptr)->next) ? ((((ptr)->next))->ranges[0][0]) : hi + 1) - lo;
               i++)
            {
              ((result)->lines[0 + d][i]) = ((result)->lines[2][linec]);
              ((result)->lengths[0 + d][i]) = ((result)->lengths[2][linec]);
              linec++;
            }
        }
    }


  if (!using[0])
    ((result)->correspond) = DIFF_2ND;
  else if (!using[1])
    ((result)->correspond) = DIFF_1ST;
  else
    {
      lin nl0 = (((result)->ranges[0][1]) - ((result)->ranges[0][0]) + 1);
      lin nl1 = (((result)->ranges[1][1]) - ((result)->ranges[1][0]) + 1);

      if (nl0 != nl1
          || !compare_line_list (((result)->lines[0]),
                                 ((result)->lengths[0]),
                                 ((result)->lines[1]),
                                 ((result)->lengths[1]),
                                 nl0))
        ((result)->correspond) = DIFF_ALL;
      else
        ((result)->correspond) = DIFF_3RD;
    }

  return result;
}






static 
      _Bool

copy_stringlist (char * const fromptrs[], size_t const fromlengths[],
                 char *toptrs[], size_t tolengths[],
                 lin copynum)
{
  register char * const *f = fromptrs;
  register char **t = toptrs;
  register size_t const *fl = fromlengths;
  register size_t *tl = tolengths;

  while (copynum--)
    {
      if (*t)
        {
          if (*fl != *tl || memcmp (*f, *t, *fl) != 0)
            return 
                  0
                       ;
        }
      else
        {
          *t = *f;
          *tl = *fl;
        }

      t++; f++; tl++; fl++;
    }

  return 
        1
            ;
}





