static uint8_t ramdata[128 * 512];

int ramdisk_init(void)
{
 uint32_t i = 0;


 uint8_t chk = 0;
 for (i = 32; i < 43; i++) {
  chk = (((chk & 1) << 7) | ((chk & 0xFE) >> 1)) + DirSector[i];
 }
 DirSector[13] = chk;


 const uint8_t text[] = "USB Mass Storage Class example. ";
 i = 0;
 while (i < sizeof(ramdata)) {
  ramdata[i] = text[i % (sizeof(text) -1)];
  i++;
 }
 return 0;
}

int ramdisk_read(uint32_t lba, uint8_t *copy_to)
{
 memset(copy_to, 0, 512);
 switch (lba) {
  case 0:
   memcpy(copy_to, BootSector, sizeof(BootSector));
   copy_to[512 - 2] = 0x55;
   copy_to[512 - 1] = 0xAA;
   break;
  case 1:
  case 2:
   memcpy(copy_to, FatSector, sizeof(FatSector));
   break;
  case 3:
   memcpy(copy_to, DirSector, sizeof(DirSector));
   break;
  default:

   if (lba >= ((1 + 2 + (512 * 32) / 512) + (3 - 2) * 4) && lba < ((1 + 2 + (512 * 32) / 512) + (3 - 2) * 4) + 128) {
    memcpy(copy_to, ramdata + (lba - ((1 + 2 + (512 * 32) / 512) + (3 - 2) * 4)) * 512, 512);
   }
   break;
 }
 return 0;
}

