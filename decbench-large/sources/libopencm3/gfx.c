void gfx_drawCircle(int16_t x0, int16_t y0, int16_t r,
      uint16_t color)
{
 int16_t f = 1 - r;
 int16_t ddF_x = 1;
 int16_t ddF_y = -2 * r;
 int16_t x = 0;
 int16_t y = r;

 gfx_drawPixel(x0 , y0+r, color);
 gfx_drawPixel(x0 , y0-r, color);
 gfx_drawPixel(x0+r, y0 , color);
 gfx_drawPixel(x0-r, y0 , color);

 while (x < y) {
  if (f >= 0) {
   y--;
   ddF_y += 2;
   f += ddF_y;
  }
  x++;
  ddF_x += 2;
  f += ddF_x;

  gfx_drawPixel(x0 + x, y0 + y, color);
  gfx_drawPixel(x0 - x, y0 + y, color);
  gfx_drawPixel(x0 + x, y0 - y, color);
  gfx_drawPixel(x0 - x, y0 - y, color);
  gfx_drawPixel(x0 + y, y0 + x, color);
  gfx_drawPixel(x0 - y, y0 + x, color);
  gfx_drawPixel(x0 + y, y0 - x, color);
  gfx_drawPixel(x0 - y, y0 - x, color);
 }
}

void gfx_drawCircleHelper(int16_t x0, int16_t y0,
     int16_t r, uint8_t cornername, uint16_t color)
{
 int16_t f = 1 - r;
 int16_t ddF_x = 1;
 int16_t ddF_y = -2 * r;
 int16_t x = 0;
 int16_t y = r;

 while (x < y) {
  if (f >= 0) {
   y--;
   ddF_y += 2;
   f += ddF_y;
  }
  x++;
  ddF_x += 2;
  f += ddF_x;
  if (cornername & 0x4) {
   gfx_drawPixel(x0 + x, y0 + y, color);
   gfx_drawPixel(x0 + y, y0 + x, color);
  }
  if (cornername & 0x2) {
   gfx_drawPixel(x0 + x, y0 - y, color);
   gfx_drawPixel(x0 + y, y0 - x, color);
  }
  if (cornername & 0x8) {
   gfx_drawPixel(x0 - y, y0 + x, color);
   gfx_drawPixel(x0 - x, y0 + y, color);
  }
  if (cornername & 0x1) {
   gfx_drawPixel(x0 - y, y0 - x, color);
   gfx_drawPixel(x0 - x, y0 - y, color);
  }
 }
}

void gfx_fillCircle(int16_t x0, int16_t y0, int16_t r,
      uint16_t color)
{
 gfx_drawFastVLine(x0, y0 - r, 2*r+1, color);
 gfx_fillCircleHelper(x0, y0, r, 3, 0, color);
}


void gfx_fillCircleHelper(int16_t x0, int16_t y0, int16_t r,
     uint8_t cornername, int16_t delta, uint16_t color)
{
 int16_t f = 1 - r;
 int16_t ddF_x = 1;
 int16_t ddF_y = -2 * r;
 int16_t x = 0;
 int16_t y = r;

 while (x < y) {
  if (f >= 0) {
   y--;
   ddF_y += 2;
   f += ddF_y;
  }
  x++;
  ddF_x += 2;
  f += ddF_x;

  if (cornername & 0x1) {
   gfx_drawFastVLine(x0+x, y0-y, 2*y+1+delta, color);
   gfx_drawFastVLine(x0+y, y0-x, 2*x+1+delta, color);
  }
  if (cornername & 0x2) {
   gfx_drawFastVLine(x0-x, y0-y, 2*y+1+delta, color);
   gfx_drawFastVLine(x0-y, y0-x, 2*x+1+delta, color);
  }
 }
}


void gfx_drawLine(int16_t x0, int16_t y0,
       int16_t x1, int16_t y1,
       uint16_t color)
{
 int16_t steep = abs(y1 - y0) > abs(x1 - x0);
 if (steep) {
  { int16_t t = x0; x0 = y0; y0 = t; };
  { int16_t t = x1; x1 = y1; y1 = t; };
 }

 if (x0 > x1) {
  { int16_t t = x0; x0 = x1; x1 = t; };
  { int16_t t = y0; y0 = y1; y1 = t; };
 }

 int16_t dx, dy;
 dx = x1 - x0;
 dy = abs(y1 - y0);

 int16_t err = dx / 2;
 int16_t ystep;

 if (y0 < y1) {
  ystep = 1;
 } else {
  ystep = -1;
 }

 for (; x0 <= x1; x0++) {
  if (steep) {
   gfx_drawPixel(y0, x0, color);
  } else {
   gfx_drawPixel(x0, y0, color);
  }
  err -= dy;
  if (err < 0) {
   y0 += ystep;
   err += dx;
  }
 }
}


void gfx_drawRect(int16_t x, int16_t y,
    int16_t w, int16_t h,
    uint16_t color)
{
 gfx_drawFastHLine(x, y, w, color);
 gfx_drawFastHLine(x, y + h - 1, w, color);
 gfx_drawFastVLine(x, y, h, color);
 gfx_drawFastVLine(x + w - 1, y, h, color);
}

