static long
parse_number (const char *arg)
{
  char *endptr = 
                ((void *)0)
                    ;
  
 (*__errno_location ()) 
       = 0;
  long result;

  if (strncmp (arg, "0x", 2) == 0)
    result = strtol (arg + 2, &endptr, 16);
  else if (strncmp (arg, "0", 1) == 0
           && strspn (arg, "012345678") == strlen (optarg))
    result = strtol (arg + 1, &endptr, 8);
  else
    result = strtol (arg, &endptr, 10);

  if (
     (*__errno_location ()) 
           != 0 || (endptr && *endptr != '\0'))
    error (
          1
                      , 
                        (*__errno_location ())
                             , "'%s' is not a recognizable number.",
           arg);

  return result;
}


static const struct option long_options[] =
{
  { "debug", 
            1
                             , 0, 'd' },
  { "index", 
            1
                             , 0, 'i' },
  { "username", 
               1
                                , 0, 'u' },
  { "passwd", 
             1
                              , 0, 'p' },
  { "salt", 
           1
                            , 0, 's' },
  { "verify", 
             0
                        , 0, 0x7f + 1 },
  { "passwd-conf", 
                  1
                                   , 0, 'v' },
  { "create-conf", 
                  1
                                   , 0, 0x7f + 2 },
  { "version", 
              2
                               , 0, 0x7f + 3 },
  { "help", 
           0
                      , 0, 'h' },
  { "more-help", 
                0
                           , 0, '!' },
  { 0, 0, 0, 0 }

};


static const char *index_default = "3";

int
process_options (int argc, char **argv)
{
  struct srptool_options *opts = &srptool_options;
  int opt;

  opts->arg.index = index_default;
  opts->value.index = 3;

  while ((opt = getopt_long (argc, argv, "!d:hi:p:s:u:v:",
                             long_options, 
                                          ((void *)0)
                                              )) != 
                                                    (-1)
                                                       )
    switch (opt)
      {
      case '\0':
        break;
      case 'd':
        opts->present.debug = 
                             1
                                 ;
        opts->arg.debug = optarg;
        opts->value.debug = parse_number(optarg);
        opts->enabled.debug = 
                             1
                                 ;
        break;
      case 'i':
        opts->present.index = 
                             1
                                 ;
        opts->arg.index = optarg;
        opts->value.index = parse_number(optarg);
        opts->enabled.index = 
                             1
                                 ;
        break;
      case 'u':
        opts->present.username = 
                                1
                                    ;
        opts->arg.username = optarg;
        opts->enabled.username = 
                                1
                                    ;
        break;
      case 'p':
        opts->present.passwd = 
                              1
                                  ;
        opts->arg.passwd = optarg;
        opts->enabled.passwd = 
                              1
                                  ;
        break;
      case 's':
        opts->present.salt = 
                            1
                                ;
        opts->arg.salt = optarg;
        opts->value.salt = parse_number(optarg);
        opts->enabled.salt = 
                            1
                                ;
        break;
      case 0x7f + 1:
        opts->present.verify = 
                              1
                                  ;
        opts->enabled.verify = 
                              1
                                  ;
        break;
      case 'v':
        opts->present.passwd_conf = 
                                   1
                                       ;
        opts->arg.passwd_conf = optarg;
        opts->enabled.passwd_conf = 
                                   1
                                       ;
        break;
      case 0x7f + 2:
        opts->present.create_conf = 
                                   1
                                       ;
        opts->arg.create_conf = optarg;
        opts->enabled.create_conf = 
                                   1
                                       ;
        break;
      case 0x7f + 3:
        opts->present.version = 
                               1
                                   ;
        opts->arg.version = optarg;
        opts->enabled.version = 
                               1
                                   ;
        break;
      case 'h':
        opts->present.help = 
                            1
                                ;
        opts->enabled.help = 
                            1
                                ;
        break;
      case '!':
        opts->present.more_help = 
                                 1
                                     ;
        opts->enabled.more_help = 
                                 1
                                     ;
        break;
      default:
        usage (
              stderr
                    , 
                      1
                                  );
        break;
      }

  if (srptool_options.present.debug && srptool_options.value.debug < 0)
    {
      error (
            1
                        , 0, "%s option value %d is out of range.",
             "debug", opts->value.debug);
    }
  if (srptool_options.present.debug && srptool_options.value.debug > 9999)
    {
      error (
            1
                        , 0, "%s option value %d is out of range",
             "debug", opts->value.debug);
    }
  if (optind < argc)
    {
      error (
            1
                        , 0, "Command line arguments are not allowed.");
    }


  if (srptool_options.present.help)
    {
      usage (
     stdout
     , (0));
    }

  if (srptool_options.present.more_help)





    {
      pid_t pid;
      int pfds[2];

      if (pipe (pfds) < 0)
        error (
              1
                          , 
                            (*__errno_location ())
                                 , "pipe");

      pid = fork ();
      if (pid < 0)
        error (
              1
                          , 
                            (*__errno_location ())
                                 , "fork");

      if (pid == 0)
        {
          close (pfds[0]);
          dup2 (pfds[1], 
                        1
                                     );
          close (pfds[1]);

          usage (
                stdout
                      , 0);
        }
      else
        {
          const char *args[2];
          const char *envvar;

          close (pfds[1]);
          dup2 (pfds[0], 
                        0
                                    );
          close (pfds[0]);

          envvar = secure_getenv ("PAGER");
          if (!envvar || *envvar == '\0')
            args[0] = "more";
          else
            args[0] = envvar;

          args[1] = 
                   ((void *)0)
                       ;

          execvp (args[0], (char * const *)args);

          exit (
               1
                           );
        }
    }


  if (srptool_options.present.version)
    {
      if (!srptool_options.arg.version || !strcmp (srptool_options.arg.version, "c"))
        {
          const char str[] =
            "srptool 3.7.8\n"
            "Copyright (C) 2000-2021 Free Software Foundation, and others\n"
            "This is free software. It is licensed for use, modification and\n"
            "redistribution under the terms of the GNU General Public License,\n"
            "version 3 or later <http://gnu.org/licenses/gpl.html>\n"
            "\n"
            "Please send bug reports to:  <bugs@gnutls.org>            \n";
          fprintf (
                  stdout
                        , "%s", str);
          exit(0);
        }
      else if (!strcmp (srptool_options.arg.version, "v"))
        {
          const char str[] =
            "srptool 3.7.8\n";
          fprintf (
                  stdout
                        , "%s", str);
          exit(0);
        }
      else if (!strcmp (srptool_options.arg.version, "n"))
        {
          const char str[] =
            "srptool 3.7.8\n"
            "Copyright (C) 2000-2021 Free Software Foundation, and others\n"
            "This is free software. It is licensed for use, modification and\n"
            "redistribution under the terms of the GNU General Public License,\n"
            "version 3 or later <http://gnu.org/licenses/gpl.html>\n"
            "\n"
            "gnutls is free software: you can redistribute it and/or\n"
            "modify it under the terms of the GNU General Public License\n"
            "as published by the Free Software Foundation,\n"
            "either version 3 of the License, or (at your option) any later version.\n"
            "\n"
            "gnutls is distributed in the hope that it will be useful,\n"
            "but WITHOUT ANY WARRANTY; without even the implied warranty\n"
            "of MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE.\n"
            "See the GNU General Public License for more details.\n"
            "\n"
            "You should have received a copy of the GNU General Public License\n"
            "along with this program.  If not, see <http://www.gnu.org/licenses/>.\n"
            "\n"
            "Please send bug reports to:  <bugs@gnutls.org>            \n";
          fprintf (
                  stdout
                        , "%s", str);
          exit(0);
        }
      else
        {
          error (
                1
                            , 0,
                 "version option argument 'a' invalid.  Use:\n"
                 "	'v' - version only\n"
                 "	'c' - version and copyright\n"
                 "	'n' - version and full copyright notice");
        }
    }

  return optind;
}

void
usage (FILE *out, int status)
{
  const char str[] =
    "srptool - GnuTLS SRP tool\n"
    "Usage:  srptool [ -<flag> [<val>] | --<name>[{=| }<val>] ]... \n"
    "\n"
    "None:\n"
    "\n"
    "   -d, --debug=num            Enable debugging\n"
    "				- it must be in the range:\n"
    "				  0 to 9999\n"
    "   -i, --index=num            specify the index of the group parameters in tpasswd.conf to use\n"
    "   -u, --username=str         specify a username\n"
    "   -p, --passwd=str           specify a password file\n"
    "   -s, --salt=num             specify salt size\n"
    "       --verify               just verify the password\n"
    "   -v, --passwd-conf=str      specify a password conf file\n"
    "       --create-conf=str      Generate a password configuration file\n"
    "\n"
    "Version, usage and configuration options:\n"
    "\n"
    "   -v, --version[=arg]        output version information and exit\n"
    "   -h, --help                 display extended usage information and exit\n"
    "   -!, --more-help            extended usage information passed thru pager\n"
    "\n"
    "Options are specified by doubled hyphens and their name or by a single\n"
    "hyphen and the flag character.\n"
    "\n"
    "Simple program that emulates the programs in the Stanford SRP (Secure\n"
    "Remote Password) libraries using GnuTLS.  It is intended for use in  places\n"
    "where you don't expect SRP authentication to be the used for system users.\n"
    "\n"
    "In  brief,  to use SRP you need to create two files. These are the password\n"
    "file that holds the users and the verifiers associated with  them  and  the\n"
    "configuration file to hold the group parameters (called tpasswd.conf).\n"
    "\n"
    "Please send bug reports to:  <bugs@gnutls.org>\n"
    "\n";
  fprintf (out, "%s", str);
  exit (status);
}
