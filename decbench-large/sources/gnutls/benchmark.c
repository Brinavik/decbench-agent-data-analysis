inline static unsigned int
timespec_sub_ms(struct timespec *a, struct timespec *b)
{
 return (a->tv_sec - b->tv_sec) * 1000 + (a->tv_nsec - b->tv_nsec) / (1000 * 1000);
}

inline static unsigned long
timespec_sub_ns(struct timespec *a, struct timespec *b)
{
 return (a->tv_sec - b->tv_sec) * 1000000000 + (a->tv_nsec - b->tv_nsec);
}



volatile int benchmark_must_finish = 0;
static void alarm_handler(int signo)
{
 benchmark_must_finish = 1;
}


static void
value2human(uint64_t bytes, double time, double *data, double *speed,
     char *metric)
{
 if (bytes > 1000 && bytes < 1000 * 1000) {
  *data = ((double) bytes) / 1000;
  *speed = *data / time;
  strcpy(metric, "KB");
  return;
 } else if (bytes >= 1000 * 1000 && bytes < 1000 * 1000 * 1000) {
  *data = ((double) bytes) / (1000 * 1000);
  *speed = *data / time;
  strcpy(metric, "MB");
  return;
 } else if (bytes >= 1000 * 1000 * 1000) {
  *data = ((double) bytes) / (1000 * 1000 * 1000);
  *speed = *data / time;
  strcpy(metric, "GB");
  return;
 } else {
  *data = (double) bytes;
  *speed = *data / time;
  strcpy(metric, "bytes");
  return;
 }
}

void start_benchmark(struct benchmark_st *st)
{
 memset(st, 0, sizeof(*st));

 st->old_handler = signal(
                         14
                                , alarm_handler);

 clock_gettime(
2
, &st->start);
 benchmark_must_finish = 0;
 alarm(5);


}


double stop_benchmark(struct benchmark_st *st, const char *metric,
        int quiet)
{
 double secs;
 unsigned long lsecs;
 struct timespec stop;
 double dspeed, ddata;
 char imetric[16];







 signal(
       14
              , st->old_handler);


 clock_gettime(
2
, &stop);

 lsecs = timespec_sub_ms(&stop, &st->start);
 secs = lsecs;
 secs /= 1000;

 if (metric == 
              ((void *)0)
                  ) {
  value2human(st->size, secs, &ddata, &dspeed, imetric);
  if (quiet == 0)
   printf("  Processed %.2f %s in %.2f secs: ", ddata,
          imetric, secs);
  printf("%.2f %s/sec\n", dspeed, imetric);
 } else {
  ddata = (double) st->size;
  dspeed = ddata / secs;
  if (quiet == 0)
   printf("  Processed %.2f %s in %.2f secs: ", ddata,
          metric, secs);
  printf("%.2f %s/sec\n", dspeed, metric);
 }

 return secs;
}
