static void force_memcpy(void *dest, const void *src, size_t n)
{
 volatile unsigned volatile_zero = 0;
 volatile char *vdest = (volatile char*)dest;

 if (n > 0) {
  do {
   memcpy(dest, src, n);
  } while(vdest[volatile_zero] != ((char*)src)[volatile_zero]);
 }
}

